package com.wtlx.infrastructure.memory.support;

/**
 * 长期记忆相关的 LLM 提示词集中管理。
 * <p>
 * 此前抽取提示词散落在抽取 Agent、冲突判定提示词散落在冲突判定器，各自维护、难以横向对照。
 * 统一收口到本类，按用途分组，便于整体审视语气口径一致性与复用。
 *
 * @author 金小梁
 */
public final class MemoryPrompts {

    private MemoryPrompts() {
    }

    // ─────────────────────────────────────────────────────────────────────────
    // 一、记忆抽取（从一段对话中识别值得长期记住的用户个性化信息）
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * 抽取提示词。
     * <p>
     * 关键设计：
     * <ul>
     *     <li><b>划定负样本</b>——明确列出"不要抽什么"比只列"要抽什么"有效得多，
     *         尤其要挡住"把助手建议当用户偏好"这一类污染；</li>
     *     <li><b>槽位白名单 + 兜底</b>——给出既有槽位让同义信息收敛，同时允许新槽位，
     *         否则模型会硬塞进不匹配的槽位，反而制造假冲突；</li>
     *     <li><b>相对时间必须绝对化</b>——"下个月去成都"若不换算成日期，
     *         记忆将永远有效，过期清理就彻底失效；</li>
     *     <li><b>由你判断是否需要抽取</b>——输入是一段（最多 10 轮）对话记录，
     *         而非单轮；你需要自行判断其中是否蕴含值得长期记住的用户个性化信息；
     *         整段都没有时直接输出 []，不要硬凑，这是噪声记忆的主要来源。</li>
     * </ul>
     */
    public static final String EXTRACTION_SYSTEM_PROMPT = """
            你是旅游平台「微途旅行」的用户长期记忆抽取器。任务：从一段（最多 10 轮）对话记录中，\
            抽取"值得跨会话长期记住"的用户个性化信息，输出严格 JSON 数组。

            ## 抽取与否由你判断
            输入是用户与助手的一段完整往返对话，不是单轮。请综合整段对话自行判断：
            是否出现了值得长期记住的用户个性化信息。若整段都没有，直接输出 []，不要硬凑。

            ## 应该抽取（跨会话仍然成立的信息）
            - 偏好：喜欢什么样的目的地 / 玩法 / 节奏
            - 避讳：不喜欢、要避开的东西
            - 硬性约束：不可协商的条件（同行人、时间限制、身体条件、预算上限）
            - 兴趣：摄影、徒步、观星、美食、历史等
            - 旅行风格：穷游 / 深度游 / 打卡 / 休闲
            - 饮食：忌口、口味、素食、清真等
            - 住宿 / 交通偏好
            - 同行情况：独自 / 情侣 / 亲子 / 朋友团
            - 预算档位
            - 明确的出行计划（带时间）

            ## 禁止抽取
            - 寒暄、情绪、对助手回答的复述或赞同
            - 助手自己推荐的方案、景点、路线（除非用户明确表示认同或已决定）
            - 通用常识、与用户个人无关的知识
            - 本轮问题本身（"成都三日游怎么安排"只是提问，不是偏好）
            - 用户明确说"随便""都行""你决定"这类无信息量的内容

            ## 槽位键（key）规范
            优先复用以下既有槽位，语义不匹配时才自拟（ASCII、点分、全小写）：
            destination.prefer, travel.style, trip.pace, interest.tag, avoid.prefer,
            budget.level, party.companion, dietary.restriction, accommodation.prefer,
            transport.prefer, season.prefer, trip.plan

            ## 字段规则
            - type：PREFERENCE / DISLIKE / CONSTRAINT / INTEREST / TRAVEL_STYLE / DIETARY /
              ACCOMMODATION / TRANSPORT / PARTY / BUDGET / TRIP_PLAN / FACT
            - content：一句完整的中文事实陈述，主语为"用户"，例如"用户喜欢徒步与自然风光"
            - structured：可结构化时给出键值对象，否则 null
            - confidence：0~1，表示"这是用户长期稳定的真实偏好"的把握程度
            - importance：0~1，表示该信息对行程规划决策的重要性
            - validTo：有时效的信息（"下个月""明年暑假""这次五一"）必须换算成绝对时间，
              格式 yyyy-MM-ddTHH:mm:ss；长期稳定的信息填 null
            - evidence：从用户原话中截取的不超过 60 字的依据片段

            ## 输出
            只输出 JSON 数组本身，不要解释、不要 Markdown 代码围栏。整段对话都没有可抽取信息时输出 []。
            示例：
            [{"type":"PREFERENCE","key":"travel.style","content":"用户喜欢徒步与自然风光，不喜欢人多拥挤的景点",\
            "structured":{"style":"自然","avoid":"拥挤"},"confidence":0.85,"importance":0.75,"validTo":null,\
            "evidence":"我喜欢徒步，最好人少一点"}]
            """;

    // ─────────────────────────────────────────────────────────────────────────
    // 二、冲突校验（判断新信息与已有记忆的合并方式，仅用于规则无法裁决的灰区）
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * 冲突判定提示词。
     * <p>
     * 刻意强调"不要因为话题相关就判冲突"——模型最容易犯的错是把
     * "喜欢徒步" 和 "预算 3000" 这类同域不同槽位的记忆判成矛盾，
     * 进而错误覆盖用户偏好。因此把"同一槽位 / 同一件事"作为判定的前置条件写死在提示里。
     */
    public static final String CONFLICT_JUDGE_SYSTEM_PROMPT = """
            你是用户长期记忆库的冲突仲裁器。给定【新信息】和若干【已有记忆】，判断新信息应该如何入库。

            判定前提：只有"针对同一件事 / 同一槽位"的信息才可能互相冲突。
            话题相关（都属于旅游）不等于冲突，例如"喜欢徒步"与"预算 3000"是两个独立事实，互不冲突。

            可选决策（必须选一个）：
            - NOOP：新信息与某条已有记忆表达的是同一个事实，只是措辞不同，且没有补充新细节
            - UPDATE：针对同一件事，新信息是已有记忆的补充或细化，两者不矛盾（例如"喜欢徒步"→"喜欢徒步，尤其高海拔线路"）
            - SUPERSEDE：针对同一件事，新信息与已有记忆的取值矛盾，用户的说法变了（例如"喜欢辣"→"不吃辣了"）
            - FORGET：用户明确否定了某条已有记忆，且这条新信息本身不需要留下（例如"我上次说喜欢人多热闹，那是我随便说的"）
            - ADD：新信息与所有已有记忆都不针对同一件事，是全新的信息

            注意：用户最新表述优先。若新信息更具体、更明确，倾向 UPDATE；若明确改口，倾向 SUPERSEDE。

            只输出 JSON 对象，不要解释、不要代码围栏：
            {"decision":"SUPERSEDE","target":2,"reason":"用户明确改口，不再接受辣味餐食","merged":null}
            - target：所针对的已有记忆序号（1 开始）；ADD 时填 null
            - merged：仅 UPDATE 需要，给出合并后的完整中文陈述；其余填 null
            """;
}
